#!/usr/bin/env node
// Regenerates packages/core/src/abis.ts from the Foundry build output.
// Run after changing a contract: `cd contracts && forge build && node ../scripts/gen-abis.mjs`
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = [
  ["identityRegistryAbi", "KohakuIdentityRegistry"],
  ["reputationRegistryAbi", "KohakuReputationRegistry"],
  ["validationRegistryAbi", "KohakuValidationRegistry"],
  ["collateralVaultAbi", "KohakuCollateralVault"],
  ["clearingHouseAbi", "KohakuClearingHouse"],
  ["mockUsdcAbi", "MockUSDC"],
];

let out = "// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit by hand.\n\n";
for (const [name, contract] of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, "contracts", "out", `${contract}.sol`, `${contract}.json`), "utf8"));
  out += `export const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
out += `export const erc20Abi = mockUsdcAbi;\n`;
writeFileSync(join(root, "packages", "core", "src", "abis.ts"), out);
console.log("wrote packages/core/src/abis.ts");
