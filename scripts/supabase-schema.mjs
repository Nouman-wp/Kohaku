#!/usr/bin/env node
// Writes supabase/schema.sql: the Postgres tables the clearing service mirrors to Supabase,
// generated from the SQLite schema in services/clearing/src/db.ts so the two never drift.
//
//   node scripts/supabase-schema.mjs        then paste supabase/schema.sql into the Supabase SQL editor
//
// Safe to run again on an existing project: tables are created if missing and new columns added.
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ROOT } from "./lib.mjs";
import { Db } from "../services/clearing/src/db.ts";
import { MIRRORED } from "../services/clearing/src/mirror.ts";

const db = new Db(mkdtempSync(join(tmpdir(), "kohaku-schema-")));
const pgType = (t) => (/INT/i.test(t) ? "bigint" : "text");

const out = [
  "-- Kohaku clearing database, mirrored from SQLite by services/clearing/src/mirror.ts.",
  "-- Generated by scripts/supabase-schema.mjs; do not edit by hand.",
  "-- Every row carries `deployment` (e.g. kohaku-hashkey-testnet-a4f5f3f3), so testnet, mainnet",
  "-- and later redeploys share one project without mixing ledgers. JSON is kept as the exact",
  "-- text the service wrote (cast with ::jsonb to query it), so a restore is byte-for-byte.",
  "-- Row level security is on with no policies: only the server's secret key can read or write.",
  "",
];
for (const [tbl, keys] of Object.entries(MIRRORED)) {
  const cols = db.all(`PRAGMA table_info(${tbl})`);
  out.push(`create table if not exists public.${tbl} (`);
  out.push("  deployment text not null,");
  for (const c of cols) out.push(`  ${c.name} ${pgType(c.type)}${c.notnull ? " not null" : ""},`);
  out.push(`  primary key (deployment, ${keys.join(", ")})`);
  out.push(");");
  // columns added to SQLite later reach an existing project when the script is run again
  for (const c of cols.filter((c) => !keys.includes(c.name))) out.push(`alter table public.${tbl} add column if not exists ${c.name} ${pgType(c.type)};`);
  out.push(`alter table public.${tbl} enable row level security;`, `grant all on public.${tbl} to service_role;`, "");
}
out.push(
  "-- The people behind the agents: every operator wallet, with what it runs and signs.",
  // group first, then count intents per group: Postgres rejects a correlated subquery that
  // reads a.operator when the query groups by lower(a.operator)
  "create or replace view public.operators with (security_invoker = true) as",
  "select o.*,",
  "       (select count(*) from public.intents i where i.deployment = o.deployment and lower(i.operator) = o.operator) as intents",
  "from (",
  "  select a.deployment,",
  "         lower(a.operator) as operator,",
  "         count(*) as agents,",
  "         string_agg(a.name, ', ' order by a.agent_id) as agent_names,",
  "         to_timestamp(min(a.registered_at) / 1000.0) as first_seen,",
  "         to_timestamp(max(a.updated_at) / 1000.0) as last_seen",
  "  from public.agents a",
  "  group by a.deployment, lower(a.operator)",
  ") o;",
  "grant select on public.operators to service_role;",
  "",
);

mkdirSync(join(ROOT, "supabase"), { recursive: true });
writeFileSync(join(ROOT, "supabase", "schema.sql"), out.join("\n"));
db.raw.close();
console.log(`wrote supabase/schema.sql (${Object.keys(MIRRORED).length} tables + operators view)`);
