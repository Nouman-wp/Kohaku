#!/usr/bin/env node
// Create every wallet and secret a public deployment needs, in .env.<network>.
// Existing values are never overwritten, so it is safe to run again.
//
//   node scripts/wallets.mjs testnet                  generate (deployer from DEPLOYER_PRIVATE_KEY if set)
//   node scripts/wallets.mjs testnet --show           print the addresses only
//
// The file is git-ignored. Back it up: it holds the keys of every agent and operator.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, addressOf, cast } from "./lib.mjs";

const network = process.argv[2] ?? "testnet";
const showOnly = process.argv.includes("--show");
if (!["testnet", "mainnet"].includes(network)) throw new Error("usage: node scripts/wallets.mjs testnet|mainnet [--show]");
const file = join(ROOT, `.env.${network}`);
const testnet = network === "testnet";

const key = () => `0x${randomBytes(32).toString("hex")}`;
const secret = (n) => randomBytes(n).toString("hex");

// what a fresh file starts from; keys are filled in below
const TEMPLATE = `# Kohaku on HashKey Chain ${testnet ? "testnet (133)" : "mainnet (177)"}. Generated by scripts/wallets.mjs.
# Git-ignored. Holds every key of this deployment: keep a backup somewhere safe.

KOHAKU_CHAIN=${testnet ? "hashkey-testnet" : "hashkey"}
RPC_URL=${testnet ? "https://testnet.hsk.xyz" : "https://mainnet.hsk.xyz"}

# ── deployment ───────────────────────────────────────────────────────────────
DEPLOYER_PRIVATE_KEY=
${
  testnet
    ? `# Empty: deploy Kohaku Test USDC (EIP-3009, open faucet). HSP's own testnet USDC is
# 0x8FE3cB719Ee4410E236Cd6b72ab1fCDC06eF53c6 (USD Coin, v2, 6 decimals, EIP-3009) and
# USDT 0x372325443233fEbaC1F6998aC750276468c83CC6, but only their owners can mint them.
# Set this to the HSP USDC once HashKey has funded the agents, and redeploy.
SETTLEMENT_TOKEN=`
    : `# USDC.e ("Bridged USDC", 6 decimals, EIP-3009, EIP-712 domain "Bridged USDC" v2).
# USDT 0xf1b50ed67a9e2cc94ad3c477779e2d4cbfff9029 has no EIP-3009 and cannot be used.
SETTLEMENT_TOKEN=0x054ed45810DbBAb8B27668922D110669c9D88D0a`
}
SETTLEMENT_WINDOW=${testnet ? "180" : "600"}
WITHDRAWAL_DELAY=${testnet ? "900" : "3600"}

# ── clearing service ─────────────────────────────────────────────────────────
CLEARER_PRIVATE_KEY=
PORT=8787
# the public base every link and agent card uses (the Vercel domain proxies to this machine)
PUBLIC_API_URL=http://localhost:8787
EPOCH_INTAKE_SECONDS=${testnet ? "90" : "600"}
EPOCH_CHALLENGE_SECONDS=20
DISPUTE_WINDOW_SECONDS=15
ARBITRATION_TIMEOUT_SECONDS=20
POST_CHUNK_SIZE=120
WRITE_REPUTATION_ONCHAIN=true
REPUTATION_EPOCH_STRIDE=${testnet ? "5" : "10"}
EPOCH_EXTEND_IDLE=true
ADMIN_TOKEN=
CORS_ORIGIN=*

# ── HSP ──────────────────────────────────────────────────────────────────────
# local:    Kohaku's own gateway serves HashKey Merchant's API and relays the payments.
# merchant: HashKey Merchant itself. Needs HSP_BASE_URL, HSP_APP_KEY, HSP_APP_SECRET from
#           HashKey, the merchant public key (pnpm wallets ${network} --show) registered with
#           them, and a SETTLEMENT_TOKEN they support.
HSP_MODE=local
${testnet ? "# HashKey Merchant QA (testnet): https://merchant-qa.hashkeymerchant.com" : "# HashKey Merchant production URL: from HashKey at onboarding"}
HSP_BASE_URL=
HSP_APP_KEY=kohaku-local-gateway
HSP_APP_SECRET=
HSP_MERCHANT_NAME=Kohaku
HSP_MERCHANT_PRIVATE_KEY=
HSP_NETWORK=${testnet ? "hashkey-testnet" : "hashkey"}
HSP_COIN=USDC
HSP_GATEWAY_RELAYER_KEY=

# ── agent fleet ──────────────────────────────────────────────────────────────
FLEET_PORT=8788
PUBLIC_FLEET_URL=http://localhost:8788
CLEARING_URL=http://localhost:8787
FLEET_SEED=
FLEET_OPERATOR_KEY=
ROGUE_OPERATOR_KEY=
FLEET_BACKGROUND=on
BACKGROUND_INTERVAL_SECONDS=${testnet ? "1800" : "3600"}
COLLATERAL_TARGET=${testnet ? "5" : "2"}
ORCHESTRATOR_COLLATERAL=${testnet ? "20" : "5"}
WALLET_TARGET=${testnet ? "5" : "1"}
GAS_TARGET=${testnet ? "0.004" : "0.5"}
GUEST_SESSIONS_PER_HOUR=10

# ── Supabase mirror (optional) ───────────────────────────────────────────────
# Project URL and secret key (Project Settings > API keys). Server side only: the key
# bypasses row level security. Leave empty to keep the mirror off.
SUPABASE_URL=
SUPABASE_SECRET_KEY=
`;

function parse(text) {
  const out = new Map();
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out.set(m[1], m[2]);
  }
  return out;
}

let text = existsSync(file) ? readFileSync(file, "utf8") : TEMPLATE;
const have = parse(text);
const set = (name, value) => {
  const re = new RegExp(`^${name}=.*$`, "m");
  text = re.test(text) ? text.replace(re, `${name}=${value}`) : `${text.trimEnd()}\n${name}=${value}\n`;
  have.set(name, value);
};

if (!showOnly) {
  const fresh = {
    DEPLOYER_PRIVATE_KEY: () => process.env.DEPLOYER_PRIVATE_KEY || key(),
    CLEARER_PRIVATE_KEY: key,
    HSP_GATEWAY_RELAYER_KEY: key,
    HSP_MERCHANT_PRIVATE_KEY: key,
    HSP_APP_SECRET: () => secret(32),
    FLEET_SEED: key,
    FLEET_OPERATOR_KEY: key,
    ROGUE_OPERATOR_KEY: key,
    ADMIN_TOKEN: () => secret(16),
  };
  let made = 0;
  for (const [name, gen] of Object.entries(fresh)) {
    if (have.get(name)) continue;
    set(name, gen());
    made++;
  }
  writeFileSync(file, text.replace(/\r\n/g, "\n"));
  console.log(made ? `wrote ${made} new value(s) to .env.${network}` : `.env.${network} already complete; nothing changed`);
}

// ── addresses ────────────────────────────────────────────────────────────────
const SLUGS = ["orchestrator", "scout", "verifier", "polyglot", "scribe", "lens", "arbiter", "rogue"];
const agentKey = (seed, slug) => cast(["keccak", `0x${seed.slice(2)}${Buffer.from(`kohaku/agent/${slug}`).toString("hex")}`]);
const rows = [
  ["deployer (funds everything)", have.get("DEPLOYER_PRIVATE_KEY")],
  ["clearing service", have.get("CLEARER_PRIVATE_KEY")],
  ["HSP gateway relayer", have.get("HSP_GATEWAY_RELAYER_KEY")],
  ["fleet operator", have.get("FLEET_OPERATOR_KEY")],
  ["rogue operator", have.get("ROGUE_OPERATOR_KEY")],
  ...SLUGS.map((s) => [`agent: ${s}`, have.get("FLEET_SEED") ? agentKey(have.get("FLEET_SEED"), s) : ""]),
].filter(([, k]) => k);
console.log(`\n${network} wallets`);
for (const [role, k] of rows) console.log(`  ${role.padEnd(30)} ${addressOf(k)}`);

const mk = have.get("HSP_MERCHANT_PRIVATE_KEY");
if (mk) {
  try {
    const { merchantKey, merchantPublicPem } = await import("../packages/core/src/hsp-node.ts");
    console.log(`\nHSP merchant public key (register it with HashKey Merchant for HSP_MODE=merchant):\n${merchantPublicPem(merchantKey(mk))}`);
  } catch (err) {
    console.log(`\n(could not print the merchant public key: ${err.message})`);
  }
}
